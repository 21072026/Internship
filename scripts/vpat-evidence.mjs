#!/usr/bin/env node
// Regenerate the VPAT and its evidence appendix (#2037).
//
//   npm run vpat:evidence
//
// Reads the accessibility gate's own artefacts — e2e/a11y-baseline.json (which
// page states are scanned and what is frozen), e2e/a11y-scan.spec.ts (the tag
// set and the gated severities) and docs/a11y-audit.md (the totals line) — plus
// git (the commit that last changed the baseline, and HEAD), and writes:
//
//   src/lib/vpatEvidence.generated.ts   the structured evidence the page and
//                                        the .md route render at runtime
//                                        (Markdown is not in the image)
//   docs/legal/vpat.md                   the report, from src/lib/vpat.ts
//   docs/legal/vpat-evidence.md          the appendix
//
// The baseline's own commit is the stamp, not "now": a regenerate that changes
// nothing produces no diff, and a stale generated file is caught by
// scripts/test/vpat.test.mjs comparing it with the baseline.
//
// Runs under `node --experimental-strip-types` so it can import the TypeScript
// data and renderer directly, exactly as the unit tests do.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
import { EN_SECTIONS, S508_SECTIONS, VPAT_META, VPAT_SELF_ASSESSMENT_ISSUE, VPAT_TRACKING_ISSUE, WCAG_AAA_NOTE, WCAG_ROWS, enChapter9Rows } from '../src/lib/vpat.ts';
import { renderEvidenceAppendix, renderVpat } from '../src/lib/vpatRender.ts';

const REPO_URL = 'https://github.com/21072026/Internship';
const BASELINE = 'e2e/a11y-baseline.json';
const SCAN_SPEC = 'e2e/a11y-scan.spec.ts';
const AUDIT = 'docs/a11y-audit.md';

function git(...args) {
  return execFileSync('git', args, { encoding: 'utf8' }).trim();
}

/** `const NAME = ['a', 'b']` / `new Set(['a', 'b'])` → ['a', 'b'] */
function stringList(source, name) {
  const m = new RegExp(`const ${name}\\s*=\\s*(?:new Set\\()?\\[([^\\]]*)\\]`).exec(source);
  if (!m) throw new Error(`${SCAN_SPEC}: could not find ${name}`);
  return [...m[1].matchAll(/'([^']+)'/g)].map((x) => x[1]);
}

export function readEvidence() {
  const baseline = JSON.parse(readFileSync(BASELINE, 'utf8'));
  const spec = readFileSync(SCAN_SPEC, 'utf8');
  const audit = readFileSync(AUDIT, 'utf8');
  const totalsMatch = /\*\*Totals\*\* — critical: (\d+) · serious: (\d+) · moderate: (\d+) · minor: (\d+)/.exec(audit);
  const [baselineCommit, baselineDate] = git('log', '-1', '--format=%H%n%cI', '--', BASELINE).split('\n');
  const pages = Object.keys(baseline).map((key) => {
    const dark = key.endsWith('#dark');
    return {
      key,
      path: dark ? key.slice(0, -'#dark'.length) : key,
      theme: dark ? 'dark' : 'light',
      violations: baseline[key],
    };
  });
  return {
    baselineCommit,
    baselineDate,
    generatedFrom: git('rev-parse', '--short', 'HEAD'),
    tags: stringList(spec, 'WCAG_TAGS'),
    gatedSeverities: stringList(spec, 'GATED_SEVERITIES'),
    pages,
    totals: totalsMatch
      ? { critical: +totalsMatch[1], serious: +totalsMatch[2], moderate: +totalsMatch[3], minor: +totalsMatch[4] }
      : null,
  };
}

export function vpatDocument() {
  return {
    meta: VPAT_META,
    wcag: WCAG_ROWS,
    aaaNote: WCAG_AAA_NOTE,
    en: EN_SECTIONS,
    enChapter9: enChapter9Rows(),
    s508: S508_SECTIONS,
    repoUrl: REPO_URL,
    trackingIssue: VPAT_TRACKING_ISSUE,
    selfAssessmentIssue: VPAT_SELF_ASSESSMENT_ISSUE,
    appendixHref: 'vpat-evidence.md',
  };
}

const evidence = readEvidence();
const generated = [
  '// GENERATED by scripts/vpat-evidence.mjs — do not edit by hand. Regenerate: npm run vpat:evidence',
  '//',
  '// The automated evidence behind the VPAT (#2037): which page states the',
  '// accessibility gate scans, under which rule set, with what frozen result,',
  "// and at which commit. Checked against e2e/a11y-baseline.json by",
  '// scripts/test/vpat.test.mjs, so a stale copy fails the build.',
  "import type { VpatEvidence } from './vpatRender';",
  '',
  `export const VPAT_EVIDENCE: VpatEvidence = ${JSON.stringify(evidence, null, 2)};`,
  '',
].join('\n');
writeFileSync('src/lib/vpatEvidence.generated.ts', generated);
writeFileSync('docs/legal/vpat.md', renderVpat(vpatDocument(), evidence));
writeFileSync('docs/legal/vpat-evidence.md', renderEvidenceAppendix(evidence, REPO_URL));

const open = evidence.pages.reduce((n, p) => n + Object.values(p.violations).reduce((s, v) => s + v, 0), 0);
console.log(
  `vpat: ${evidence.pages.length} page states from ${BASELINE} @ ${evidence.baselineCommit.slice(0, 7)} (${evidence.baselineDate.slice(0, 10)}), ` +
    `${open} frozen finding(s), tags ${evidence.tags.join(',')} → docs/legal/vpat.md, docs/legal/vpat-evidence.md, src/lib/vpatEvidence.generated.ts`,
);
