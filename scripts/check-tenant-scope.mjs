#!/usr/bin/env node
// Guard: every API route has a declared tenant-scope state (#1570).
//
// WHY THIS EXISTS
//   docs/tenant-isolation.md used to say, in prose, that "all authenticated API
//   routes that query a tenant-anchored model are now wrapped". Nothing checked
//   the sentence, and it was wrong the day it was written. Before
//   MT_ENFORCE_ISOLATION changes the behaviour of every route file, each one
//   needs a state a machine can verify:
//
//     scoped     the handler binds the caller's org: `withTenantScope(session, …)`
//                (a session) or `withApiKey(…)` (an API key, which runs the
//                handler inside runWithApiKeyOrg). Detected from the source.
//     listed     deliberately not wrapped, with a written reason, in
//                scripts/tenant-scope-routes.mjs — `public` (no session: a token,
//                a signature, a secret or a typed address names the subject),
//                `explicit` (every tenant query names the caller's org itself,
//                or a super-admin gate guards the cross-tenant read) or
//                `own-rows` (only the caller's own rows, keyed by user id).
//     pending    NOT DONE: an authenticated route whose tenant reads could not be
//                shown to be narrowed. A ratchet, pinned by EXPECTED_PENDING in
//                that file — the list only shrinks.
//
//   Anything else fails: a new route that is neither wrapped nor listed, an
//   entry naming a route that no longer exists (the rename foot-gun
//   check-demo-blocklist.mjs exists for), an entry for a route that has since
//   been wrapped (stale), and an entry without a reason.
//
//   One more signal, printed but not fatal: a `public` route that references a
//   tenant model (`prisma.<model>.`). Its reason must say how the token or the
//   address — not a session — picks the row.
//
// THE LEDGER
//   The table in docs/tenant-isolation.md between the route-ledger markers is
//   GENERATED from this check (`--write`); CI runs check mode, so the doc fails
//   the build when it goes stale.
//
// Run: node scripts/check-tenant-scope.mjs [--write]   (npm run check:tenant-scope)

import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';
import { EXPECTED_PENDING, LISTED_ROUTES, PENDING_ROUTES } from './tenant-scope-routes.mjs';

const API_DIR = 'src/app/api';
const ORG_CONTEXT_FILE = 'src/lib/orgContext.ts';
const DOC_FILE = 'docs/tenant-isolation.md';
const BEGIN = '<!-- BEGIN route-ledger (generated by scripts/check-tenant-scope.mjs --write; do not edit) -->';
const END = '<!-- END route-ledger -->';
const KINDS = new Set(['public', 'explicit', 'own-rows']);
const SCOPED = /\bwithTenantScope\s*\(|\bwithApiKey\s*\(/;

function routeFiles(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...routeFiles(p));
    else if (name === 'route.ts') out.push(relative(API_DIR, p).split(sep).join('/'));
  }
  return out.sort();
}

// The registered tenant models, as the `prisma.<camelName>.` they appear as.
function tenantModelAccessors() {
  const src = readFileSync(ORG_CONTEXT_FILE, 'utf8');
  const start = src.indexOf('const TENANT_MODELS');
  const block = src.slice(start, src.indexOf(']);', start));
  const names = [...block.replace(/\/\/.*$/gm, '').matchAll(/'([A-Z][A-Za-z0-9]*)'/g)].map((m) => m[1]);
  return names.map((n) => n[0].toLowerCase() + n.slice(1));
}

const routes = routeFiles(API_DIR);
const present = new Set(routes);
const accessors = tenantModelAccessors();
const problems = [];
const notes = [];

for (const [route, entry] of [...LISTED_ROUTES, ...PENDING_ROUTES]) {
  if (!present.has(route)) problems.push(`${route}: listed in scripts/tenant-scope-routes.mjs but no such route exists (renamed or removed?) — update or drop the entry.`);
}
for (const [route, entry] of LISTED_ROUTES) {
  if (!KINDS.has(entry.kind)) problems.push(`${route}: kind '${entry.kind}' is not one of ${[...KINDS].join(' | ')}.`);
  if (!entry.reason?.trim()) problems.push(`${route}: a listed route needs its reason written down.`);
}
for (const [route, reason] of PENDING_ROUTES) {
  if (!reason?.trim()) problems.push(`${route}: a pending route needs the gap written down.`);
  if (LISTED_ROUTES.has(route)) problems.push(`${route}: both listed and pending — pick one.`);
}
if (PENDING_ROUTES.size !== EXPECTED_PENDING) {
  problems.push(
    `PENDING_ROUTES holds ${PENDING_ROUTES.size} route(s), EXPECTED_PENDING says ${EXPECTED_PENDING}. ` +
      'Scoping a route means deleting its entry AND lowering the number in the same diff; the list never grows.',
  );
}

const rows = [];
for (const route of routes) {
  const src = readFileSync(join(API_DIR, route), 'utf8');
  const scoped = SCOPED.test(src);
  const listed = LISTED_ROUTES.get(route);
  const pending = PENDING_ROUTES.get(route);
  if (scoped) {
    if (listed || pending) problems.push(`${route}: now wrapped — its entry in scripts/tenant-scope-routes.mjs is stale; delete it${pending ? ' and lower EXPECTED_PENDING' : ''}.`);
    rows.push({ route, state: 'scoped', reason: /\bwithApiKey\s*\(/.test(src) && !/\bwithTenantScope\s*\(/.test(src) ? 'API key: runWithApiKeyOrg' : '' });
    continue;
  }
  if (listed) {
    if (listed.kind === 'public') {
      const touched = accessors.filter((a) => src.includes(`prisma.${a}.`));
      if (touched.length) notes.push(`${route} (public) reads tenant model(s) ${touched.join(', ')} — reason: ${listed.reason}`);
    }
    rows.push({ route, state: listed.kind, reason: listed.reason });
    continue;
  }
  if (pending) {
    rows.push({ route, state: 'pending', reason: pending });
    continue;
  }
  problems.push(
    `${route}: neither wrapped nor listed. Wrap the handler in withTenantScope(session, …) — or, if it must stay ` +
      'unwrapped, add it to LISTED_ROUTES in scripts/tenant-scope-routes.mjs with its kind and reason.',
  );
}

const counts = rows.reduce((m, r) => ((m[r.state] = (m[r.state] ?? 0) + 1), m), {});
const esc = (s) => s.replace(/\|/g, '\\|');
const table = [
  `${routes.length} route files under \`src/app/api\`: ` +
    ['scoped', 'explicit', 'own-rows', 'public', 'pending'].map((k) => `${counts[k] ?? 0} ${k}`).join(', ') + '.',
  '',
  '| Route | State | Why it is not wrapped |',
  '|---|---|---|',
  ...rows.map((r) => `| \`${r.route.replace(/\/route\.ts$/, '') || '/'}\` | ${r.state} | ${esc(r.reason)} |`),
].join('\n');

const doc = readFileSync(DOC_FILE, 'utf8');
const b = doc.indexOf(BEGIN);
const e = doc.indexOf(END);
if (b < 0 || e < b) {
  problems.push(`${DOC_FILE}: the route-ledger markers are missing.`);
} else {
  const next = `${doc.slice(0, b + BEGIN.length)}\n${table}\n${doc.slice(e)}`;
  if (process.argv.includes('--write')) {
    if (next !== doc) writeFileSync(DOC_FILE, next);
  } else if (next !== doc) {
    problems.push(`${DOC_FILE}: the route ledger is stale — run \`node scripts/check-tenant-scope.mjs --write\` and commit the result.`);
  }
}

for (const n of notes) console.log(`note: ${n}`);
if (problems.length) {
  for (const p of problems) console.error(`::error::${p}`);
  console.error(`check:tenant-scope FAILED — ${problems.length} problem(s).`);
  process.exit(1);
}
console.log(
  `check:tenant-scope OK — ${routes.length} routes: ` +
    Object.entries(counts).map(([k, v]) => `${v} ${k}`).join(', ') +
    (PENDING_ROUTES.size ? ` (${PENDING_ROUTES.size} pending: the ratchet in scripts/tenant-scope-routes.mjs)` : ''),
);
